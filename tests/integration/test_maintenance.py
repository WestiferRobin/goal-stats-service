"""Real Alembic generation against owned TEST PostgreSQL and temporary revisions."""

import os
import shutil
from contextlib import contextmanager
from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import Column, Integer, Table, text
from sqlalchemy.exc import DBAPIError

from infra.resources.db import Database, verify_import_database
from models.base import Base
from settings.base import ConfigurationError
from settings.database import ImportTarget
from settings.environment import load_application

ROOT = Path(__file__).resolve().parents[2]


@contextmanager
def comparison(database, config, target):
    """Test Alembic against a verified disposable database in a read-only transaction."""
    target.validate(database.engine.url)
    with database.sessions() as session:
        session.execute(text("SET TRANSACTION ISOLATION LEVEL REPEATABLE READ, READ ONLY"))
        verify_import_database(session, target)
        config.attributes["connection"] = session.connection()
        try:
            yield
        finally:
            config.attributes.pop("connection", None)


def test_real_generation_and_read_only_check(postgres_config, tmp_path):
    # postgres_config authorizes the disposable provider before any connection.
    database = Database(load_application(postgres_config).database)
    target = ImportTarget("test", database.engine.url.host, database.engine.url.database)
    shutil.copytree(ROOT / "alembic", tmp_path / "alembic")
    shutil.copy(ROOT / "alembic.ini", tmp_path / "alembic.ini")
    config = Config(str(tmp_path / "alembic.ini"))
    versions = tmp_path / "alembic/versions"
    before = {p.name: p.read_bytes() for p in versions.glob("*.py")}
    table = None
    try:
        with comparison(database, config, target):
            command.check(config)
        assert {p.name: p.read_bytes() for p in versions.glob("*.py")} == before
        with database.engine.begin() as connection:
            head = connection.scalar(text("SELECT version_num FROM alembic_version"))
            connection.execute(text("UPDATE alembic_version SET version_num='f6b82d14c903'"))
        try:
            with pytest.raises(ConfigurationError, match="not current"):
                with comparison(database, config, target):
                    command.check(config)
        finally:
            with database.engine.begin() as connection:
                connection.execute(
                    text("UPDATE alembic_version SET version_num=:head"), {"head": head}
                )
        table = Table(
            "maintenance_test_only", Base.metadata, Column("id", Integer, primary_key=True)
        )
        with pytest.raises(AutogenerateDiffsDetected):
            with comparison(database, config, target):
                command.check(config)
        with comparison(database, config, target):
            command.revision(config, autogenerate=True, message="isolated generated revision")
        created = [p for p in versions.glob("*.py") if p.name not in before]
        assert len(created) == 1
        assert "maintenance_test_only" in created[0].read_text()
        assert created[0].stat().st_uid == os.getuid()
        assert created[0].stat().st_mode & 0o600 == 0o600
        assert all((versions / name).read_bytes() == value for name, value in before.items())
        with database.engine.connect() as connection:
            assert connection.scalar(text("SELECT to_regclass('maintenance_test_only')")) is None

        # PostgreSQL itself must reject writes through the comparison connection.
        with pytest.raises(DBAPIError, match="read-only"):
            with comparison(database, config, target):
                config.attributes["connection"].execute(
                    text("CREATE TABLE forbidden_write (id int)")
                )
    finally:
        if table is not None:
            Base.metadata.remove(table)
        database.dispose()
