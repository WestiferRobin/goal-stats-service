CREATE TABLE predictions (
    prediction_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    scenario_id INTEGER NOT NULL,
    generated_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    model_version VARCHAR(80) NOT NULL,
    team1_win_probability DOUBLE PRECISION NOT NULL,
    draw_probability DOUBLE PRECISION NOT NULL,
    team2_win_probability DOUBLE PRECISION NOT NULL,
    team1_expected_remaining_goals DOUBLE PRECISION,
    team2_expected_remaining_goals DOUBLE PRECISION,
    most_likely_team1_score SMALLINT,
    most_likely_team2_score SMALLINT,
    input_snapshot JSONB NOT NULL,
    details JSONB NOT NULL,
    CONSTRAINT pk_predictions PRIMARY KEY (prediction_id),
    CONSTRAINT ck_predictions_details_object CHECK (jsonb_typeof(details) = 'object'),
    CONSTRAINT ck_predictions_draw_probability_range CHECK (draw_probability BETWEEN 0 AND 1),
    CONSTRAINT ck_predictions_input_snapshot_object CHECK (jsonb_typeof(input_snapshot) = 'object'),
    CONSTRAINT ck_predictions_model_version_nonblank CHECK (model_version ~ '[^[:space:]]'),
    CONSTRAINT ck_predictions_probability_sum CHECK (abs(team1_win_probability + draw_probability + team2_win_probability - 1) <= 1e-9),
    CONSTRAINT ck_predictions_team1_expected_goals_finite CHECK (team1_expected_remaining_goals >= 0 AND team1_expected_remaining_goals < 'Infinity'::float8),
    CONSTRAINT ck_predictions_team1_probability_range CHECK (team1_win_probability BETWEEN 0 AND 1),
    CONSTRAINT ck_predictions_team1_score_nonnegative CHECK (most_likely_team1_score >= 0),
    CONSTRAINT ck_predictions_team2_expected_goals_finite CHECK (team2_expected_remaining_goals >= 0 AND team2_expected_remaining_goals < 'Infinity'::float8),
    CONSTRAINT ck_predictions_team2_probability_range CHECK (team2_win_probability BETWEEN 0 AND 1),
    CONSTRAINT ck_predictions_team2_score_nonnegative CHECK (most_likely_team2_score >= 0),
    CONSTRAINT fk_predictions_scenario_id_scenarios FOREIGN KEY(scenario_id) REFERENCES scenarios (scenario_id) ON DELETE RESTRICT
);

CREATE INDEX ix_predictions_scenario_id ON predictions (scenario_id, generated_at, prediction_id);

CREATE INDEX ix_predictions_generated_at ON predictions (generated_at, prediction_id);

